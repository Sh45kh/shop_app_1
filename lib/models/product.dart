class Product {
  final String id;
  final String name;
  final double price;
  final String brand;
  final String category;
  final String inStock;
  final String imageUrl;
  final String description;

  Product({
    required this.id,
    required this.name,
    required this.price,
    required this.brand,
    required this.category,
    required this.inStock,
    required this.imageUrl,
    required this.description,
  });
}